// Voice-call simulation. A local demo: no telephony, no microphone, no recording.
// Every caller turn is sent to the server, which runs the same guided assistant
// as the website. Reading replies aloud is optional and uses the browser only.
(function () {
  const $ = (id) => document.getElementById(id);
  const phone = document.querySelector(".phone");
  const log = $("chat-log");
  const optionsBox = $("chat-options");
  const form = $("call-form");
  const input = $("call-input");
  const sayButton = form.querySelector("button");
  const startButton = $("call-start");
  const muteButton = $("call-mute");
  const endButton = $("call-end");
  const shortcuts = [...document.querySelectorAll(".shortcut")];
  const calm = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
  const canSpeak = "speechSynthesis" in window && "SpeechSynthesisUtterance" in window;
  const QUIET = new Set(["reset", "skip", "more", "change_date", "change_time", "waitlist"]);

  let callId = null;
  let state = null;
  let busy = false;
  let muted = false;
  let startedAt = 0;
  let ticker = null;
  let lastOptions = [];

  function el(tag, props, ...children) {
    const node = Object.assign(document.createElement(tag), props || {});
    node.append(...children);
    return node;
  }
  const pause = (ms) => new Promise((resolve) => setTimeout(resolve, calm ? 0 : ms));
  const scrollDown = () => (log.scrollTop = log.scrollHeight);

  async function api(path, body) {
    let response;
    try {
      response = await fetch(path, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify(body || {}),
      });
    } catch (_) {
      throw new Error("Could not reach the demo server. Please check it is running and try again.");
    }
    const data = await response.json().catch(() => ({}));
    if (!response.ok) throw new Error(data.message || "Something went wrong. Please try again.");
    return data;
  }

  // --- Voice (optional) -------------------------------------------------------
  // Browser speech synthesis only, and never required. It does not autoplay: nothing
  // is spoken until the presenter has clicked or pressed a key. Wherever speech is
  // unreliable or missing the page runs in "text simulation mode": no speech is
  // attempted, no failure is shown, and the transcript carries the whole demo.
  const TEST_PHRASE = "Hello. This is the Smriti Raj Dentistry appointment assistant.";
  const panel = $("audio-panel");
  const testButton = $("audio-test");
  const STATUS_TEXT = {
    ready: "Voice ready",
    muted: "Muted",
    "needs-click": "Audio requires a click to start",
    text: panel.dataset.textMessage,
  };
  const REASONS = { firefox: panel.dataset.reasonFirefox, "no-voice": panel.dataset.reasonNoVoice, failed: panel.dataset.reasonFailed };
  // Firefox (notably on Linux) often has no usable speech engine, so it always uses text mode.
  const isFirefox = document.body.dataset.textMode === "firefox" || /firefox|fxios/i.test(navigator.userAgent);
  const synth = canSpeak && !isFirefox ? window.speechSynthesis : null;

  // A natural voice generated by the demo server on this computer, when the optional voice
  // pack is installed. It plays as ordinary audio, so it works in every browser, Firefox included.
  let serverVoice = panel.dataset.serverVoice === "1";
  const player = new Audio();
  let playing = null; // object URL of the reply being played
  let speechSeq = 0; // increases whenever speech is replaced or stopped

  let voices = [];
  let voicesChecked = false; // true once the browser has had a fair chance to list its voices
  let interacted = false; // browsers only allow speech after a user gesture
  let speechOffForCall = false; // speech failed to start once: stay in text mode until the next call
  let heard = false; // an utterance has actually started at least once
  let utterances = []; // keep references so the browser does not drop queued speech
  let speakTimer = null;
  let watchdog = null;

  // Why the page is in text simulation mode, or null when speech can be used.
  function textModeReason() {
    if (serverVoice) return speechOffForCall ? "failed" : null;
    if (isFirefox) return "firefox";
    if (!synth || (voicesChecked && !voices.length && !heard)) return "no-voice";
    if (speechOffForCall) return "failed";
    return null;
  }

  function audioState() {
    if (textModeReason()) return "text";
    if (muted) return "muted";
    if (!interacted) return "needs-click";
    return "ready";
  }

  function showAudio(notice) {
    const current = audioState();
    const reason = textModeReason();
    $("audio-status").dataset.state = current;
    $("audio-status-text").textContent = STATUS_TEXT[current];
    // In text mode the speaker test and mute control stay visible but inactive, with the reason on hover.
    if (reason) {
      testButton.setAttribute("aria-disabled", "true");
      testButton.title = REASONS[reason];
    } else {
      testButton.removeAttribute("aria-disabled");
      testButton.removeAttribute("title");
    }
    muteButton.disabled = !!reason;
    $("call-mute-label").textContent = reason ? "Voice off" : muted ? "Voice muted" : "Mute voice";
    const box = $("audio-notice");
    box.textContent = notice || "";
    box.hidden = !notice;
  }

  function loadVoices() {
    if (!synth) return;
    const read = () => {
      const list = synth.getVoices();
      if (!list.length) return false;
      voices = list;
      voicesChecked = true;
      showAudio();
      return true;
    };
    if (read()) return;
    // Chrome-family browsers fill the list asynchronously and announce it with this event.
    synth.onvoiceschanged = read;
    setTimeout(() => {
      if (!read()) {
        voicesChecked = true;
        showAudio();
      }
    }, 2500);
  }

  // Choose the voice deliberately. Prefer English (India); otherwise the browser's default
  // voice if it is English; otherwise another plain English voice. Some speech engines list
  // thousands of voices, including distorted "variant" ones (names like "English+whisper")
  // and non-English defaults, which is what makes speech sound wrong or garbled.
  function preferredVoice() {
    const lang = (v) => (v.lang || "").replace("_", "-").toLowerCase();
    const english = voices.filter((v) => lang(v) === "en" || lang(v).startsWith("en-"));
    const plain = english.filter((v) => !v.name.includes("+"));
    const pool = plain.length ? plain : english;
    return (
      pool.find((v) => lang(v) === "en-in") ||
      pool.find((v) => v.default) ||
      pool.find((v) => lang(v) === "en-gb") ||
      pool.find((v) => lang(v) === "en-us") ||
      pool[0] ||
      null
    );
  }

  function hush() {
    speechSeq += 1;
    clearTimeout(speakTimer);
    clearTimeout(watchdog);
    utterances = [];
    player.pause();
    if (playing) URL.revokeObjectURL(playing);
    playing = null;
    if (synth) synth.cancel();
  }

  async function playFromServer(text) {
    const seq = speechSeq;
    try {
      const response = await fetch("/api/call-demo/speech", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ text }),
      });
      if (seq !== speechSeq) return; // a newer reply, mute or end-call replaced this one
      if (response.status === 503) {
        serverVoice = false; // voice pack gone: carry on with the browser voice or text mode
        return showAudio();
      }
      if (!response.ok) return fallBackToText();
      const blob = await response.blob();
      if (seq !== speechSeq) return;
      playing = URL.createObjectURL(blob);
      player.src = playing;
      await player.play();
      heard = true;
      showAudio();
    } catch (error) {
      if (seq !== speechSeq || error.name === "AbortError") return;
      if (error.name === "NotAllowedError") {
        interacted = false; // the browser wants a fresh click first; not a failure
        return showAudio();
      }
      fallBackToText();
    }
  }

  // Speech did not start: finish this call as a text simulation rather than keep retrying.
  function fallBackToText() {
    speechOffForCall = true;
    hush();
    showAudio();
  }

  function speak(lines) {
    if (textModeReason()) return; // text simulation mode: never touch the speech engine
    hush(); // a new reply replaces anything still queued from the previous one
    if (muted || !interacted) return showAudio();
    if (serverVoice) return void playFromServer(lines.join("\n"));
    // Short lines are spoken whole; long ones go sentence by sentence, which some
    // browsers need to avoid cutting off lengthy speech.
    const parts = lines
      .flatMap((line) => line.replace(/[•#·]/g, " ").split(line.length > 160 ? /(?<=[.?!])\s+|\n+/ : /\n+/))
      .map((part) => part.trim())
      .filter(Boolean);
    if (!parts.length) return;
    const voice = preferredVoice();
    // Chrome can drop speak() calls made in the same tick as cancel(), so queue just after it.
    speakTimer = setTimeout(() => {
      let started = false;
      synth.resume();
      for (const part of parts) {
        const utterance = new SpeechSynthesisUtterance(part);
        if (voice) {
          utterance.voice = voice;
          utterance.lang = voice.lang;
        } else {
          // No English voice is listed: leave the browser's default voice in charge,
          // but still tell it the text is English.
          utterance.lang = "en-IN";
        }
        utterance.onstart = () => {
          started = heard = true;
          clearTimeout(watchdog);
          showAudio();
        };
        utterance.onerror = (event) => {
          if (event.error === "interrupted" || event.error === "canceled") return;
          if (event.error === "not-allowed") {
            interacted = false; // the browser wants a fresh click first; not a failure
            return showAudio();
          }
          fallBackToText();
        };
        utterances.push(utterance);
        synth.speak(utterance);
      }
      watchdog = setTimeout(() => {
        if (!started && !muted) fallBackToText();
      }, 4000);
    }, 80);
  }

  function setMuted(value) {
    muted = value;
    muteButton.setAttribute("aria-pressed", String(value));
    if (value) hush();
    showAudio();
  }

  function testSpeaker() {
    interacted = true;
    const reason = textModeReason();
    if (reason) return showAudio(REASONS[reason]);
    if (muted) return showAudio("Voice is muted. Choose “Voice muted” to turn it back on, then test again.");
    showAudio();
    speak([TEST_PHRASE]);
  }

  // The first click or key press anywhere on the page is what allows audio to start.
  for (const type of ["pointerdown", "keydown"]) {
    document.addEventListener(
      type,
      () => {
        if (interacted) return;
        interacted = true;
        showAudio();
      },
      { capture: true }
    );
  }

  // --- Transcript ---------------------------------------------------------------
  function addMessage(text, who, tone) {
    const names = { bot: "AI assistant", user: "Caller" };
    const node = el("div", { className: `msg msg-${who}` + (tone ? ` msg-${tone}` : ""), textContent: text });
    if (names[who]) node.dataset.who = names[who];
    log.append(node);
    scrollDown();
  }

  function addReceipt(title, rows, status) {
    const list = el("dl");
    for (const [term, detail] of rows) list.append(el("dt", { textContent: term }), el("dd", { textContent: detail }));
    list.append(
      el("dt", { textContent: "Status" }),
      el("dd", null, el("span", { className: "pill pill-" + status.toLowerCase(), textContent: status.replace("_", " ") }))
    );
    log.append(el("div", { className: "receipt" }, el("h3", { textContent: title }), list));
    scrollDown();
  }

  function renderOptions(options) {
    lastOptions = options;
    optionsBox.replaceChildren();
    for (const option of options) {
      const quiet = QUIET.has(option.action) || option.label === "No thanks" || option.label === "Speak to a person";
      const button = el("button", { type: "button", className: "chat-option" + (quiet ? " is-quiet" : ""), textContent: option.label });
      button.addEventListener("click", () => say({ action: option.action, value: option.value }, option.label));
      optionsBox.append(button);
    }
  }

  function showCaller(call) {
    const name = call.caller_name;
    $("caller-name").textContent = name || "Unknown caller";
    $("caller-mobile").textContent = call.caller_mobile || "Number not given yet";
    $("caller-avatar").textContent = name ? name.trim().charAt(0).toUpperCase() : "?";
  }

  async function render(reply) {
    state = reply.state;
    speak(reply.messages.map((message) => message.text));
    for (const message of reply.messages) {
      addMessage(message.text, "bot", message.tone);
      await pause(220);
    }
    if (reply.booking) {
      const b = reply.booking;
      addReceipt(
        "Booking request",
        [["Reference", "#" + b.reference], ["Visit", b.service], ["Doctor", b.doctor], ["When", `${b.date} at ${b.time} (${b.duration_minutes} min)`]],
        b.status
      );
    }
    if (reply.callback) {
      addReceipt("Callback request", [["Reference", reply.callback.reference], ["We will call", reply.callback.mobile]], reply.callback.status);
    }
    renderOptions(reply.options);
    const spec = reply.input || {};
    input.type = spec.type || "text";
    input.inputMode = spec.type === "tel" ? "tel" : spec.type === "email" ? "email" : "text";
    input.placeholder = spec.type && spec.type !== "text" ? spec.placeholder : spec.label === "Your message" || !spec.label ? "Type what the caller says" : spec.placeholder;
    $("call-label").textContent = spec.label && spec.label !== "Your message" ? spec.label : "What the caller says";
  }

  // --- Call lifecycle -------------------------------------------------------------
  function setBusy(value) {
    busy = value;
    sayButton.disabled = value || !callId;
    startButton.disabled = value;
    for (const button of [...shortcuts, ...optionsBox.querySelectorAll("button")]) button.disabled = value;
  }

  function tick() {
    const seconds = Math.floor((Date.now() - startedAt) / 1000);
    $("call-timer").textContent = String(Math.floor(seconds / 60)).padStart(2, "0") + ":" + String(seconds % 60).padStart(2, "0");
  }

  function showIdle(message) {
    callId = null;
    state = null;
    clearInterval(ticker);
    phone.classList.remove("is-live");
    startButton.hidden = false;
    muteButton.hidden = true;
    endButton.hidden = true;
    input.disabled = true;
    sayButton.disabled = true;
    input.type = "text";
    input.placeholder = "Type what the caller says";
    $("call-state").textContent = message;
    renderOptions([]);
  }

  function clearScreen() {
    hush();
    log.replaceChildren(el("p", { className: "call-empty", id: "call-empty", textContent: "Press “Start demo call” or choose a caller phrase below to begin." }));
    $("call-timer").textContent = "00:00";
    $("call-outcome").textContent = "";
    showCaller({});
  }

  async function startCall() {
    if (callId || busy) return;
    setBusy(true);
    clearScreen();
    try {
      const data = await api("/api/call-demo/start");
      callId = data.call.id;
      log.replaceChildren();
      addMessage("Call connected · simulated", "system");
      phone.classList.add("is-live");
      startButton.hidden = true;
      muteButton.hidden = false;
      endButton.hidden = false;
      speechOffForCall = false; // every call gets a fresh chance at speech
      showAudio();
      input.disabled = false;
      $("call-state").textContent = "Connected";
      startedAt = Date.now();
      ticker = setInterval(tick, 500);
      await render(data.reply);
    } catch (error) {
      log.replaceChildren();
      addMessage(error.message, "bot", "notice");
      showIdle("Ready to start");
    } finally {
      setBusy(false);
    }
  }

  async function say(payload, echo) {
    if (busy) return;
    if (!callId) await startCall();
    if (!callId) return;
    setBusy(true);
    hush();
    addMessage(echo, "user");
    const typing = el("div", { className: "typing", ariaLabel: "Assistant is replying" }, el("i"), el("i"), el("i"));
    log.append(typing);
    scrollDown();
    try {
      const [data] = await Promise.all([
        api(`/api/call-demo/${callId}/message`, { text: "", action: null, value: null, ...payload, state }),
        pause(420),
      ]);
      typing.remove();
      showCaller(data.call);
      await render(data.reply);
    } catch (error) {
      typing.remove();
      addMessage(error.message, "bot", "notice");
      renderOptions(lastOptions);
    } finally {
      setBusy(false);
      if (payload.text !== undefined) input.focus({ preventScroll: true });
    }
  }

  async function endCall(quiet) {
    if (!callId) return;
    const id = callId;
    hush();
    showIdle("Call ended");
    try {
      const data = await api(`/api/call-demo/${id}/end`);
      if (!quiet) {
        addMessage("Call ended", "system");
        $("call-outcome").replaceChildren("Outcome recorded for this demo call: ", el("strong", { textContent: data.call.outcome }));
      }
    } catch (error) {
      if (!quiet) addMessage(error.message, "bot", "notice");
    }
  }

  async function resetCall() {
    await endCall(true);
    clearScreen();
    showIdle("Ready to start");
    speechOffForCall = false;
    setMuted(false);
    startButton.focus();
  }

  startButton.addEventListener("click", startCall);
  endButton.addEventListener("click", () => endCall(false));
  $("call-reset").addEventListener("click", resetCall);
  muteButton.addEventListener("click", () => setMuted(!muted));
  $("audio-test").addEventListener("click", testSpeaker);
  for (const button of shortcuts) {
    button.addEventListener("click", () => say({ action: "say", value: button.dataset.phrase }, button.dataset.phrase));
  }
  form.addEventListener("submit", (event) => {
    event.preventDefault();
    const text = input.value.trim();
    if (!text || busy || !callId) return;
    input.value = "";
    say({ text }, text);
  });
  // Leaving the page closes the open demo call so the dashboard does not show it as in progress.
  window.addEventListener("pagehide", () => {
    hush();
    if (callId) navigator.sendBeacon(`/api/call-demo/${callId}/end`);
  });

  showIdle("Ready to start");
  loadVoices();
  showAudio();
})();
