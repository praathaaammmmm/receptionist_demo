"""Optional reference voice for the voice agent demo: a consented, local voice-cloning experiment.

The voice is generated by a separate local worker (scripts/reference_voice_worker.py, Chatterbox
Multilingual) conditioned on clips cut from a recording whose speaker has agreed to this demo use.
Nothing leaves this machine: the worker listens on 127.0.0.1 only, and neither it nor this module
stores the reference clips, the text or the generated speech. Generated audio is returned once and
not cached.

Whenever the reference voice cannot speak a reply (no clips, worker not running, language not
supported, too slow, failed or cancelled), synthesize_reference_voice() says why, and the caller
falls back to the standard Piper voice and labels it as such. It is never presented as the
reference voice.

Not production-ready: a demo experiment only.
"""
import asyncio
import re
import time
from dataclasses import dataclass

import httpx

from .. import config

BACKEND = "chatterbox-multilingual"
# Demo language -> the model's language id. Hinglish keeps its current behaviour: it is spoken from the
# Hindi version of each approved line, so it uses the Hindi voice profile.
LANGUAGES = {"en": "en", "hi": "hi", "hinglish": "hi"}
REQUIRED_CLIPS = ("hi_1", "mix_1")
# Safety: the cloning model misread "112" in testing, so any sentence with the emergency number is always
# spoken by the standard voice (and the page says so).
EMERGENCY_NUMBER = re.compile(r"(?<!\d)112(?!\d)")
_DIGIT_WORDS = {
    "en": "zero one two three four five six seven eight nine".split(),
    "hi": "शून्य एक दो तीन चार पाँच छह सात आठ नौ".split(),
}
_NUMBER_WORDS = {  # whole numbers that appear in approved lines (hours, fee, sector, plot)
    "en": {"8": "eight", "9": "nine", "13": "thirteen", "54": "fifty four", "500": "five hundred"},
    "hi": {"8": "आठ", "9": "नौ", "13": "तेरह", "54": "चौवन", "500": "पाँच सौ"},
}
FALLBACK_MESSAGE = "Reference voice is unavailable for this reply. Using the standard local voice."


@dataclass(frozen=True)
class SpeechResult:
    audio: bytes | None  # WAV bytes, or None when the reference voice could not speak this reply
    backend: str  # BACKEND, or "piper" once the caller has fallen back
    latency_ms: int
    fallback_reason: str | None = None
    generation_ms: int | None = None  # time the worker spent generating


def clips_present() -> bool:
    return all((config.VOICE_AGENT_REFERENCE_DIR / f"{name}.wav").is_file() for name in REQUIRED_CLIPS)


def status(timeout: float = 0.4) -> dict:
    """Whether the page may offer the reference voice: clips present and the local worker ready."""
    if not clips_present():
        return {"available": False, "reason": "No authorised reference clips are installed."}
    try:
        health = httpx.get(f"{config.VOICE_AGENT_REFERENCE_WORKER_URL}/health", timeout=timeout).json()
    except Exception:  # noqa: BLE001 - not running, or not reachable
        return {"available": False, "reason": "The local reference-voice worker is not running."}
    if not health.get("ready"):
        return {"available": False, "reason": "The reference-voice worker has no voice profile loaded."}
    return {"available": True, "backend": BACKEND, "model": health.get("model"), "licence": health.get("licence"),
            "device": health.get("device"), "languages": [code for code, model_id in LANGUAGES.items()
                                                         if model_id in health.get("languages", [])]}


def speakable(text: str, model_language: str) -> str:
    """Numbers written out for the cloning model, which misreads digits. Used for this request only, never stored."""
    words = _NUMBER_WORDS[model_language]

    def number(match: re.Match) -> str:
        digits = match.group()
        return words.get(digits) or " ".join(_DIGIT_WORDS[model_language][int(d)] for d in digits)

    return re.sub(r"\d+", number, text)


async def _cancel(client: httpx.AsyncClient, request_id: str) -> None:
    try:
        await client.post(f"{config.VOICE_AGENT_REFERENCE_WORKER_URL}/cancel", json={"request_id": request_id}, timeout=1)
    except Exception:  # noqa: BLE001
        pass


async def synthesize_reference_voice(text: str, language: str, request_id: str,
                                     cancelled: asyncio.Event | None = None) -> SpeechResult:
    """Speech for one sentence in the reference voice, or a SpeechResult with audio=None and the reason."""
    started = time.perf_counter()

    def result(audio=None, reason=None, generation_ms=None) -> SpeechResult:
        return SpeechResult(audio, BACKEND, round((time.perf_counter() - started) * 1000), reason, generation_ms)

    model_language = LANGUAGES.get(language)
    if model_language is None:
        return result(reason="language not supported by the reference voice")
    if EMERGENCY_NUMBER.search(text):
        return result(reason="emergency instructions always use the standard voice")
    if not clips_present():
        return result(reason="no authorised reference clips installed")
    async with httpx.AsyncClient() as client:
        request = asyncio.ensure_future(client.post(
            f"{config.VOICE_AGENT_REFERENCE_WORKER_URL}/synthesize",
            json={"text": speakable(text, model_language), "language": model_language, "request_id": request_id},
            timeout=config.VOICE_AGENT_REFERENCE_TIMEOUT_SECONDS))
        waits = {request}
        stop = asyncio.ensure_future(cancelled.wait()) if cancelled is not None else None
        if stop is not None:
            waits.add(stop)
        try:
            done, _ = await asyncio.wait(waits, timeout=config.VOICE_AGENT_REFERENCE_TIMEOUT_SECONDS,
                                         return_when=asyncio.FIRST_COMPLETED)
            if request not in done:
                request.cancel()
                await _cancel(client, request_id)  # a queued generation is skipped by the worker
                return result(reason="cancelled" if stop is not None and stop in done else "too slow")
            try:
                response = request.result()
            except httpx.HTTPError:
                return result(reason="the local reference-voice worker is not running")
        finally:
            if stop is not None:
                stop.cancel()
        if response.status_code == 422:
            return result(reason="language not supported by the reference voice")
        if response.status_code != 200 or response.headers.get("content-type") != "audio/wav":
            return result(reason="reference voice generation failed")
        generation = response.headers.get("X-Generation-Ms")
        return result(audio=response.content, generation_ms=int(generation) if generation else None)
