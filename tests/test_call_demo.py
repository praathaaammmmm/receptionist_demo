def test_ending_a_call_with_no_result_records_ended(call, client):
    log = call.end()
    assert log["outcome"] == "ENDED"
    assert log["completed_at"] is not None
    assert log["appointment_id"] is None and log["callback_task_id"] is None
    assert log["caller_name"] is None

    # Ending twice is harmless, and an ended call accepts no further turns.
    assert call.end() == log
    refused = client.post(f"/api/call-demo/{call.id}/message", json={"text": "hello"})
    assert refused.status_code == 400
    assert "ended" in refused.json()["message"]
    assert client.post("/api/call-demo/9999/end").status_code == 404
    assert "ENDED" in client.get("/").text


def test_abandoned_booking_keeps_caller_details_but_ends_without_outcome(call):
    reply = call.shortcut("I need to book a consultation.")
    call.pick(reply, "New patient")
    call.send("Half Finished")
    log = call.end()
    assert log["outcome"] == "ENDED"
    assert log["caller_name"] == "Half Finished"
    assert log["appointment_id"] is None


FIREFOX_UA = "Mozilla/5.0 (X11; Linux x86_64; rv:157.0) Gecko/20100101 Firefox/157.0"
CHROME_UA = "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/150.0.0.0 Safari/537.36"
TEXT_MODE = "Text simulation mode — the conversation transcript remains fully functional."


def test_firefox_gets_text_simulation_mode_by_default(client):
    page = client.get("/call-demo", headers={"user-agent": FIREFOX_UA}).text
    assert 'data-text-mode="firefox"' in page
    status = page.split('id="audio-status"')[1].split("</p>")[0]
    assert 'data-state="text"' in status
    assert TEXT_MODE in status
    assert "Audio requires a click to start" not in status
    # The speaker test stays visible but inactive, with a short explanation on hover.
    button = page.split('id="audio-test"')[1].split(">")[0]
    assert 'aria-disabled="true"' in button
    assert "Voice is switched off in Firefox" in button
    # Nothing error-like is shown, and the rest of the call screen is intact.
    for alarming in ("unavailable", "failed to", "error"):
        assert alarming not in status.lower()
    assert "Start demo call" in page and "Live transcript" in page and "Reset demo call" in page


def test_other_browsers_keep_the_speaker_controls(client):
    page = client.get("/call-demo", headers={"user-agent": CHROME_UA}).text
    assert "data-text-mode=" not in page
    status = page.split('id="audio-status"')[1].split("</p>")[0]
    assert 'data-state="needs-click"' in status
    assert "Audio requires a click to start" in status
    assert 'aria-disabled' not in page.split('id="audio-test"')[1].split(">")[0]
    # The fallback wording is still on the page for the script to use if speech fails once.
    assert TEXT_MODE in page
    assert "this call continues as a text simulation" in page


def test_call_flow_is_identical_in_text_simulation_mode(client):
    """Speech is purely a browser-side extra: the call, callback and log work the same from Firefox."""
    client.headers["user-agent"] = FIREFOX_UA
    call = Call(client)
    reply = call.shortcut("What are your opening hours?")
    assert reply["messages"][0]["text"] == knowledge.CLINIC_HOURS
    call.shortcut("I want to speak to a person.")
    call.send("Ravi Example")
    call.send("5550900009")
    log = call.end()
    assert log["outcome"] == "CALLBACK_CREATED"
    assert client.get("/api/callbacks").json()[0]["status"] == "OPEN"
    assert "AI call activity" in client.get("/").text
