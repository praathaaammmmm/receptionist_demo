"""Optional local voice (Piper) for the call demo."""
import io
import wave

import pytest

from app.services import tts

FIREFOX_UA = "Mozilla/5.0 (X11; Linux x86_64; rv:157.0) Gecko/20100101 Firefox/157.0"
FAKE_WAV = b"RIFF\x24\x00\x00\x00WAVEfmt fake-audio"


@pytest.fixture
def voice_installed(monkeypatch):
    """Pretend the voice pack is installed, without loading a real model."""
    spoken = []
    monkeypatch.setattr(tts, "available", lambda language="en": True)
    monkeypatch.setattr(tts, "synthesize", lambda text, language="en": spoken.append(text) or FAKE_WAV)
    return spoken


def test_without_voice_pack_the_demo_reports_it_and_stays_usable(client):
    assert client.get("/api/call-demo/voice").json()["available"] is False
    refused = client.post("/api/call-demo/speech", json={"text": "Hello"})
    assert refused.status_code == 503
    assert refused.json()["error"] == "voice_unavailable"
    page = client.get("/call-demo").text
    assert "data-server-voice" not in page
    assert "Audio is generated by this browser for the demo." in page
    assert client.post("/api/call-demo/start").status_code == 201  # the call itself is unaffected


def test_with_voice_pack_speech_is_served_as_audio(client, voice_installed):
    status = client.get("/api/call-demo/voice").json()
    assert status["available"] is True and status["runs"] == "locally"
    response = client.post("/api/call-demo/speech", json={"text": "Hello. This is the Smriti Raj Dentistry appointment assistant."})
    assert response.status_code == 200
    assert response.headers["content-type"] == "audio/wav"
    assert response.content == FAKE_WAV
    assert voice_installed == ["Hello. This is the Smriti Raj Dentistry appointment assistant."]


def test_with_voice_pack_every_browser_gets_voice_including_firefox(client, voice_installed):
    for agent in (FIREFOX_UA, "Mozilla/5.0 Chrome/150.0 Safari/537.36"):
        page = client.get("/call-demo", headers={"user-agent": agent}).text
        assert 'data-server-voice="1"' in page
        assert "data-text-mode=" not in page
        assert 'data-state="needs-click"' in page.split('id="audio-status"')[1].split("</p>")[0]
        assert "aria-disabled" not in page.split('id="audio-test"')[1].split(">")[0]
        assert "Audio is generated on this computer for the demo." in page


def test_speech_text_is_validated_and_made_speakable(client):
    assert tts.prepare("• Mobile: 5550800001\n• When: Tue, 13 Oct at 4:45 PM") == "Mobile: 5 5 5 0 8 0 0 0 0 1. When: Tue, 13 Oct at 4:45 PM"
    assert tts.prepare("Your reference is #6.") == "Your reference is number 6."
    with pytest.raises(tts.ValidationError):
        tts.synthesize("   ")
    with pytest.raises(tts.ValidationError):
        tts.synthesize("word " * 400)
    assert client.post("/api/call-demo/speech", json={"text": "x" * 2500}).status_code == 422


@pytest.mark.real_voice
def test_real_voice_pack_produces_playable_audio():
    if not tts.available():
        pytest.skip("voice pack not installed (run scripts/download_voice.py)")
    audio = tts.synthesize("Hello. This is the Smriti Raj Dentistry appointment assistant.")
    with wave.open(io.BytesIO(audio)) as wav:
        seconds = wav.getnframes() / wav.getframerate()
    assert 2 < seconds < 10
    assert tts.synthesize("Hello. This is the Smriti Raj Dentistry appointment assistant.") is audio  # cached


def test_speaker_is_resolved_by_name_or_number(monkeypatch, tmp_path):
    monkeypatch.setattr("app.config.VOICE_DIR", tmp_path)
    monkeypatch.setattr("app.config.VOICE_ENGLISH", "multi")
    (tmp_path / "multi.onnx.json").write_text('{"speaker_id_map": {"SVBI": 2, "ASI": 10}}')
    for wanted, expected in (("", None), ("SVBI", 2), ("10", 10), ("nobody", None)):
        monkeypatch.setattr("app.config.VOICE_ENGLISH_SPEAKER", wanted)
        assert tts.speaker_id("en") == expected
